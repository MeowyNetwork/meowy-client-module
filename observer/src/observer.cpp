// gmsv_meowy_observer: the observer's module, loaded in the menu state of a
// GMod client we run ourselves (never in a player's game). It runs the
// observer's menu Lua, which takes a job from the supervisor, joins that
// server, and puts the sampler into the game's client Lua state.
//
//   observer.RunClient(code)  -> true, or false and a reason
//   observer.ReadJob()        -> the job file's text, or nil
//   observer.WriteDone(text)  -> writes the done file for the supervisor
//
// The job and done files live in $MEOWY_OBSERVER_DIR, outside the game:
// garrysmod/data is writable by any server's client Lua, so nothing the
// observer trusts comes from there. Both Lua scripts are compiled in
// (observer_lua.h, generated by CMake from ../lua).
//
// The client state is reached through lua_shared's LUASHARED003 interface
// (ILuaShared::GetLuaInterface) and driven only through ILuaBase, the same
// API as every binary module.

