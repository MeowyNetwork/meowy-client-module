//! The pack's production policy keys, read from `src/policy.cpp` (the only
//! copy), so the launcher can never trust a different key than the pack.
//! Writes `$OUT_DIR/policy_keys.rs` with RELEASE / OPS / RECOVERY as
//! `Option<[u8; 64]>` (X || Y of each P-256 point): None while the pack has
//! none (`kReleaseKey = nullptr`).

use std::path::Path;

fn array(src: &str, name: &str) -> Option<Vec<u8>> {
    let start = src.find(&format!("const uint8_t {name}[64] = {{"))?;
    let body = &src[start..];
    let body = &body[body.find('{')? + 1..body.find('}')?];
    let bytes: Vec<u8> = body
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(|s| u8::from_str_radix(s.trim_start_matches("0x"), 16).expect("a hex byte in policy.cpp"))
        .collect();
    assert_eq!(bytes.len(), 64, "{name} in src/policy.cpp must be 64 bytes");
    Some(bytes)
}

fn main() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/policy.cpp");
    println!("cargo:rerun-if-changed={}", path.display());
    let src = std::fs::read_to_string(&path).unwrap_or_default();
    if src.is_empty() {
        println!("cargo:warning=src/policy.cpp not found: the launcher trusts no policy key");
    }
    let mut out = String::from("// Generated by build.rs from src/policy.cpp.\n");
    for (rust, cpp, used) in [("RELEASE", "kRelease", "kReleaseKey"), ("OPS", "kOps", "kOpsKey"), ("RECOVERY", "kRecovery", "kRecoveryKey")] {
        // Only a key the pack itself uses (`kReleaseKey = kRelease;`), not one left nullptr.
        let in_use = src.contains(&format!("{used} = {cpp};"));
        let value = match (in_use, array(&src, cpp)) {
            (true, Some(b)) => format!("Some({b:?})"),
            _ => "None".into(),
        };
        out += &format!("pub const {rust}: Option<[u8; 64]> = {value};\n");
    }
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("policy_keys.rs"), out).unwrap();
}
